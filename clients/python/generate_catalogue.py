"""Writes sg's verb layer from the repository's verb catalogue (catalogue/verbs/*.json) and its Python stubs
(generated/verbs/stubs/*.py, which the C# tests generate from the same catalogue):

- sg/_catalogue.py: the tables sg and its worker read (verbs, topics, each what's main list, the whats that write);
- sg/_verbs.py: one function per verb, sg.find(what, **options) ... sg.undo(id=..., **options), with the script
  options of all its whats as keyword arguments and a one-line docstring pointing at sg.help(verb, what);
- sg/_verbs.pyi: the stubs for IDEs, one @overload per what, as `help {verb, what, lang: "python"}` gives them.

    py -3 clients/python/generate_catalogue.py           write them
    py -3 clients/python/generate_catalogue.py --check   exit 1 if any is stale (tests/test_generated.py does this)

Run it whenever catalogue/verbs changes (after the C# tests rewrite generated/verbs).
"""
import json
import keyword
import pprint
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPOSITORY = HERE.parent.parent
VERB_CATALOGUE = REPOSITORY / "catalogue" / "verbs"
STUBS = REPOSITORY / "generated" / "verbs" / "stubs"
PACKAGE = HERE / "sg"

# Verbs sg does not get a generated function for: help is sg.help (it takes topics too), and run_script is what
# runs sg, not something sg calls.
NOT_GENERATED = ("help", "run_script")

# Options a script passes although the catalogue marks them x-script: drop. undo's id is dropped there, but the
# scripts help topic and the hub contract undo by id (undo {id: "script-14"}), so sg.undo takes it.
EXTRA_OPTIONS = {"undo": ["id"]}

# Names the generated functions use themselves.
RESERVED = ("what", "options")

HEADER = '"""Generated by clients/python/generate_catalogue.py from catalogue/verbs. Do not edit; run it again."""'


def load():
    """The shared file and each verb's file, in the catalogue's verb order."""
    shared = json.loads((VERB_CATALOGUE / "_shared.json").read_text(encoding="utf-8"))
    verbs = [json.loads((VERB_CATALOGUE / f"{name}.json").read_text(encoding="utf-8")) for name in shared["verbs"]]
    return shared, verbs


def resolve(option, shared):
    """An option with its shared definition (`use`) filled in, as the C# VerbCatalogue.Resolve does."""
    if "use" not in option:
        return option
    resolved = dict(shared["options"][option["use"]])
    resolved.update({key: value for key, value in option.items() if key != "use"})
    return resolved


def script_options(verb, shared):
    """The keyword options of a verb's function: fields first, then each what's options that a script takes, in
    first-seen order (EXTRA_OPTIONS before them)."""
    names = ["fields"]
    for what in verb["whats"].values():
        for name, option in (what.get("options") or {}).items():
            if resolve(option, shared).get("x-script") != "drop" and name not in names:
                names.append(name)
    for name in EXTRA_OPTIONS.get(verb["verb"], []):
        if name not in names:
            names.insert(0, name)
    for name in names:
        if keyword.iskeyword(name) or not name.isidentifier() or name in RESERVED:
            raise SystemExit(f"option '{name}' of {verb['verb']} cannot be a Python keyword argument")
    return names


def has_whats(verb):
    return list(verb["whats"]) != ["-"]


def first_sentence(text):
    text = " ".join(text.split())
    end = text.find(". ")
    return text if end < 0 else text[:end + 1]


def render_catalogue(shared, verbs):
    main_lists, write_whats, whats = {}, {}, {}
    for verb in verbs:
        name = verb["verb"]
        whats[name] = tuple(verb["whats"])
        writing = tuple(what for what, source in verb["whats"].items() if source.get("write"))
        if writing:
            write_whats[name] = writing
        for what, source in verb["whats"].items():
            listed = (source.get("reply") or {}).get("list")
            if listed:
                main_lists[(name, what)] = listed
    lines = [
        HEADER,
        "# fmt: off",
        "",
        "# Every verb, in the catalogue's order.",
        f"VERBS = {tuple(shared['verbs'])!r}",
        "",
        "# The help topics: sg.help('scripts'), sg.help('types', 'BuildJob').",
        f"TOPICS = {tuple(shared['topics'])!r}",
        "",
        "# Each verb's whats ('-' for a verb that takes none).",
        "WHATS = " + pprint.pformat(whats, width=116, sort_dicts=False),
        "",
        "# The whats that write (they carry a write block in the catalogue), per verb.",
        "WRITE_WHATS = " + pprint.pformat(write_whats, width=116, sort_dicts=False),
        "",
        "# Each (verb, what)'s main list: the reply key a for loop walks (reply.list in the catalogue).",
        "MAIN_LISTS = " + pprint.pformat(main_lists, width=116, sort_dicts=False),
        "",
    ]
    return "\n".join(lines)


def render_verbs(shared, verbs):
    lines = [
        HEADER,
        "# fmt: off",
        "from ._calls import verb_call",
        "",
        "# Each function sends `verb {verb, what, args}` to the hub. Keyword options left as None are not sent; any other",
        "# option the hub knows may be passed through **options.",
    ]
    for verb in verbs:
        name = verb["verb"]
        if name in NOT_GENERATED:
            continue
        options = script_options(verb, shared)
        keywords = ", ".join(f"{option}=None" for option in options)
        passing = ", ".join(f"{option!r}: {option}" for option in options)
        summary = first_sentence(verb["description"]).rstrip(".")
        if has_whats(verb):
            signature = f"what, *, {keywords}, **options"
            doc = f"{summary}. sg.help('{name}', what) gives a what in full."
            what = "what"
        else:
            signature = f"*, {keywords}, **options"
            doc = f"{summary}. sg.help('{name}') gives it in full."
            what = "None"
        lines += ["", ""]
        lines += textwrap.wrap(f"def {name}({signature}):", width=116, subsequent_indent="        ",
                               break_long_words=False, break_on_hyphens=False)
        lines.append(f'    """{doc}"""')
        lines += textwrap.wrap(f"return verb_call({name!r}, {what}, {{{passing}}}, options)", width=116,
                               initial_indent="    ", subsequent_indent="                     ",
                               break_long_words=False, break_on_hyphens=False)
    return "\n".join(lines) + "\n"


def read_stub(verb, what):
    filename = f"{verb}.py" if what == "-" else f"{verb}.{what}.py"
    return (STUBS / filename).read_text(encoding="utf-8").replace("\r\n", "\n")


def add_extra_options(verb, stub):
    """The stub with EXTRA_OPTIONS added as its first keyword options (the stub generator left them out)."""
    for name in EXTRA_OPTIONS.get(verb, []):
        opening = stub.index("*,\n") + len("*,\n")
        stub = stub[:opening] + f"    {name}: str | list[str] = None,  # see sg.help('{verb}')\n" + stub[opening:]
    return stub


def render_stubs(verbs):
    lines = [
        HEADER,
        "# The stubs for IDEs: each function's options and reply per what, as sg.help(verb, what) gives them.",
        "# fmt: off",
        "from typing import Literal, overload",
        "",
    ]
    for verb in verbs:
        name = verb["verb"]
        if name in NOT_GENERATED:
            continue
        overloaded = len(verb["whats"]) > 1
        for what in verb["whats"]:
            stub = add_extra_options(name, read_stub(name, what)).rstrip("\n")
            lines += (["@overload"] if overloaded else []) + [stub, ""]
    return "\n".join(lines)


def render_all():
    """{file name in sg/: its text}."""
    shared, verbs = load()
    return {
        "_catalogue.py": render_catalogue(shared, verbs),
        "_verbs.py": render_verbs(shared, verbs),
        "_verbs.pyi": render_stubs(verbs),
    }


def current(name):
    """A generated file as it is on disk, line ends normalised (a Windows checkout may have turned them to CRLF)."""
    path = PACKAGE / name
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None


def main(argv):
    rendered = render_all()
    stale = [name for name, text in rendered.items() if current(name) != text]
    if "--check" in argv:
        for name in stale:
            print(f"sg/{name} is stale against catalogue/verbs; run py -3 {Path(__file__).name}", file=sys.stderr)
        if not stale:
            print("up to date")
        return 1 if stale else 0
    for name in stale:
        (PACKAGE / name).write_text(rendered[name], encoding="utf-8", newline="\n")
        print(f"wrote sg/{name}")
    if not stale:
        print("up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
